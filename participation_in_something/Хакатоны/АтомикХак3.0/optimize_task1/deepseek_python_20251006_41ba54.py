import pandas as pd
import numpy as np

# Номинальные мощности оборудования
P_nom_DGU = 30  # кВт
P_nom_S = 15     # кВт  
P_nom_SNE = 10   # кВт
C_SNE = 50       # кВт*ч
P_nag = 60       # кВт

# Минимальная мощность ДГУ
P_min_DGU = 0.5 * P_nom_DGU  # 15 кВт

# Стоимости электроэнергии
cost_DGU = 5  # у.е./кВт*ч
cost_grid_0_6 = 9  # у.е./кВт*ч (00:00-06:00)
cost_grid_7_23 = 11  # у.е./кВт*ч (07:00-23:00)

# Данные из таблицы 1
data = {
    'time': ['00:00', '01:00', '02:00', '03:00', '04:00', '05:00', '06:00', '07:00',
             '08:00', '09:00', '10:00', '11:00', '12:00', '13:00', '14:00', '15:00',
             '16:00', '17:00', '18:00', '19:00', '20:00', '21:00', '22:00', '23:00'],
    'solar_pu': [0.6, 0.55, 0.5, 0.45, 0.4, 0.4, 0.45, 0.5, 0.55, 0.6, 0.65, 0.7, 
                 0.75, 0.8, 0.85, 0.9, 0.95, 1.0, 0.95, 0.9, 0.85, 0.8, 0.75, 0.7],
    'load_pu': [0.5, 0.45, 0.4, 0.4, 0.45, 0.5, 0.6, 0.7, 0.8, 0.85, 0.9, 0.95,
                1.0, 0.95, 0.9, 0.85, 0.9, 1.0, 0.95, 0.8, 0.7, 0.6, 0.55, 0.5]
}

df = pd.DataFrame(data)

# Пересчет из о.е. в кВт
df['P_solar'] = df['solar_pu'] * P_nom_S
# print(df['load_pu'])
# print(P_nom_DGU)
df['P_load'] = df['load_pu'] * P_nag  # Нагрузка в кВт от номинала ДГУ

# Баланс мощности: P_DGU + P_solar + P_grid = P_load
# Отсюда: P_grid = P_load - P_solar - P_DGU

# Инициализация колонок
df['P_DGU'] = 0.0
df['P_grid'] = 0.0

# Логика оптимизации для каждого часа
for i, row in df.iterrows():
    hour = int(row['time'].split(':')[0])
    P_load = row['P_load']
    P_solar = row['P_solar']
    
    # Определяем стоимость сети для текущего часа
    if 0 <= hour <= 6:
        grid_cost = cost_grid_0_6
    else:
        grid_cost = cost_grid_7_23
    
    # Вычисляем мощность, которую нужно покрыть
    power_needed = P_load - P_solar
    
    # Логика принятия решений:
    if power_needed <= 0:
        # Избыток мощности - отдаем в сеть (но не получаем доход)
        df.at[i, 'P_DGU'] = 0
        df.at[i, 'P_grid'] = power_needed  # отрицательное значение - отдача в сеть
    
    else:
        # Нужно покрыть дефицит мощности
        # Сравниваем стоимость ДГУ и сети
        if cost_DGU <= grid_cost:
            # ДГУ дешевле - используем его
            if power_needed >= P_min_DGU:
                # Потребность больше минимальной мощности ДГУ
                if power_needed <= P_nom_DGU:
                    # Потребность в пределах номинала ДГУ
                    df.at[i, 'P_DGU'] = power_needed
                    df.at[i, 'P_grid'] = 0
                else:
                    # Потребность превышает номинал ДГУ
                    df.at[i, 'P_DGU'] = P_nom_DGU
                    df.at[i, 'P_grid'] = power_needed - P_nom_DGU
            else:
                # Потребность меньше минимальной мощности ДГУ
                # Используем сеть (дороже, но вынужденно)
                df.at[i, 'P_DGU'] = 0
                df.at[i, 'P_grid'] = power_needed
        else:
            # Сеть дешевле - используем сеть
            df.at[i, 'P_DGU'] = 0
            df.at[i, 'P_grid'] = power_needed

# Округление для красоты
df['P_DGU'] = df['P_DGU'].round(2)
df['P_grid'] = df['P_grid'].round(2)

# Выбор только нужных колонок для результата
print(df)


